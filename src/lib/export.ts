// Generate shareable link (encrypted)
export async function generateShareableLink(entry: HistoryEntry): Promise<string> {
  // Compress and encode the entry data
  const jsonString = JSON.stringify({
    mode: entry.mode,
    input: entry.input,
    output: entry.output,
    engine: entry.engine,
    timestamp: entry.timestamp
  })
  
  // Base64 encode
  const encoded = btoa(encodeURIComponent(jsonString))
  
  // Create shareable URL (in production, this would be a backend endpoint)
  const baseUrl = window.location.origin
  const shareUrl = `${baseUrl}?share=${encoded}`
  
  // Copy to clipboard
  await navigator.clipboard.writeText(shareUrl)
  
  return shareUrl
}

// Decode shareable link
export function decodeShareableLink(encodedData: string): HistoryEntry | null {
  try {
    const decoded = decodeURIComponent(atob(encodedData))
    const data = JSON.parse(decoded)
    return {
      id: `shared-${Date.now()}`,
      mode: data.mode,
      input: data.input,
      output: data.output,
      engine: data.engine,
      timestamp: data.timestamp
    }
  } catch (error) {
    console.error('Failed to decode shareable link:', error)
    return null
  }
}

// Batch export multiple entries
export function exportMultipleEntriesAsMarkdown(entries: HistoryEntry[]): void {
  let markdown = `# AI Analysis Collection\n\n`
  markdown += `**Exported:** ${new Date().toLocaleString()}\n`
  markdown += `**Total Entries:** ${entries.length}\n\n`
  markdown += `---\n\n`
  
  entries.forEach((entry, index) => {
    markdown += `# Entry ${index + 1}: ${entry.mode}\n\n`
    markdown += exportToMarkdown(entry)
    markdown += `\n\n---\n\n`
  })
  
  const filename = `analysis-collection-${Date.now()}.md`
  downloadFile(markdown, filename, 'text/markdown')
}

export function exportMultipleEntriesAsJSON(entries: HistoryEntry[]): void {
  const exportData = {
    exportedAt: new Date().toISOString(),
    totalEntries: entries.length,
    version: '1.0',
    source: 'The Keys System Tri-Core AI',
    entries: entries.map(entry => ({
      timestamp: new Date(entry.timestamp).toISOString(),
      mode: entry.mode,
      engine: entry.engine,
      input: entry.input,
      output: entry.output
    }))
  }
  
  const json = JSON.stringify(exportData, null, 2)
  const filename = `analysis-collection-${Date.now()}.json`
  downloadFile(json, filename, 'application/json')
}
