import { HistoryEntry } from './history'

// Export to Markdown
export function exportToMarkdown(entry: HistoryEntry): string {
  const timestamp = new Date(entry.timestamp).toLocaleString()
  
  let markdown = `# AI Analysis Export\n\n`
  markdown += `**Date:** ${timestamp}\n`
  markdown += `**Mode:** ${entry.mode}\n`
  markdown += `**Engine:** ${entry.engine || 'Unknown'}\n\n`
  markdown += `---\n\n`
  markdown += `## Input\n\n${entry.input}\n\n`
  markdown += `---\n\n`
  
  if (typeof entry.output === 'string') {
    markdown += `## Output\n\n${entry.output}\n\n`
  } else {
    // Tri-core results
    if (entry.output.chadrak) {
      markdown += `## Chadrak Core Analysis\n\n${entry.output.chadrak}\n\n`
    }
    if (entry.output.nova) {
      markdown += `## Nova Core Analysis\n\n${entry.output.nova}\n\n`
    }
    if (entry.output.triad) {
      markdown += `## Triad Core Analysis\n\n${entry.output.triad}\n\n`
    }
  }
  
  markdown += `---\n\n`
  markdown += `*Generated by The Keys System Tri-Core AI*\n`
  
  return markdown
}

// Export to JSON
export function exportToJSON(entry: HistoryEntry): string {
  const exportData = {
    timestamp: new Date(entry.timestamp).toISOString(),
    mode: entry.mode,
    engine: entry.engine,
    input: entry.input,
    output: entry.output,
    metadata: {
      exportedAt: new Date().toISOString(),
      version: '1.0',
      source: 'The Keys System Tri-Core AI'
    }
  }
  
  return JSON.stringify(exportData, null, 2)
}

